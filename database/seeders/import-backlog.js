// Builds backend/data/backlog.json and documentation/REQUIREMENTS_COVERAGE.md from the Jira CSV export.
// Usage: node database/seeders/import-backlog.js [path-to-export.csv]
const fs = require('fs');
const path = require('path');
const trace = require('./data/traceability');

const root = path.join(__dirname, '..', '..');
const source = process.argv[2] || path.join(root, 'documentation', 'jira', 'SACA_backlog_export.csv');

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i += 1; } else if (ch === '"') quoted = false; else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); field = '';
      if (row.some((v) => v !== '')) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}

function splitDescription(raw) {
  const parts = raw.split(' || ');
  const out = { description: parts[0].trim(), acceptance_criteria: [], contributors: [] };
  for (const p of parts.slice(1)) {
    if (p.startsWith('Acceptance Criteria:')) {
      out.acceptance_criteria = p.replace('Acceptance Criteria:', '').split(/\s*\d+\)\s+/).map((s) => s.trim()).filter(Boolean);
    } else if (p.startsWith('Contributors:')) {
      out.contributors = p.replace('Contributors:', '').split(';').map((s) => {
        const m = s.trim().match(/^(.*?)\s*\((.*)\)$/);
        return m ? { name: m[1], role: m[2] } : { name: s.trim(), role: '' };
      }).filter((c) => c.name);
    }
  }
  return out;
}

const rows = parseCsv(fs.readFileSync(source, 'utf8').replace(/^\uFEFF/, ''));
const items = rows.map((r) => {
  const key = r['Issue Key'];
  const t = trace.items[key];
  if (!t) throw new Error(`No traceability entry for ${key}`);
  const d = splitDescription(r.Description);
  return {
    key,
    type: r['Issue Type'],
    summary: r.Summary,
    description: d.description,
    acceptance_criteria: d.acceptance_criteria,
    contributors: d.contributors,
    assignee: r.Assignee || null,
    priority: r.Priority,
    labels: r.Labels ? r.Labels.split(/\s+/) : [],
    start_date: r['Start Date'] || null,
    due_date: r['Due Date'] || null,
    estimate_hours: r['Original Estimate'] ? Math.round((Number(r['Original Estimate']) / 3600) * 10) / 10 : null,
    parent: r.Parent || trace.parents[key] || null,
    parent_source: r.Parent ? 'jira' : trace.parents[key] ? 'inferred' : null,
    implementation: { status: t.impl, module: t.module, evidence: t.evidence, notes: t.notes },
  };
});
const unmapped = Object.keys(trace.items).filter((k) => !items.find((i) => i.key === k));
if (unmapped.length) throw new Error(`Traceability entries without a backlog row: ${unmapped.join(', ')}`);

const count = (pred) => items.filter(pred).length;
const summary = {
  total: items.length,
  epics: count((i) => i.type === 'Epic'),
  stories: count((i) => i.type === 'Story'),
  tasks: count((i) => i.type === 'Task'),
  implementation: Object.fromEntries(['implemented', 'partial', 'outstanding', 'process'].map((s) => [s, count((i) => i.implementation.status === s)])),
  estimate_hours: Math.round(items.filter((i) => i.type === 'Task').reduce((n, i) => n + (i.estimate_hours || 0), 0) * 10) / 10,
};
const data = {
  source: 'Jira CSV export (SACA_backlog_Import_No_Assignee_No_Parent.csv)',
  live_sync: false,
  project: { name: 'Smart Advent Calendar App (SACA)', timeline: { start: '2026-10-12', end: '2026-11-12' }, backlog_window: { start: '2026-11-02', end: '2026-11-12' } },
  team: ['Dhrruv More', 'Nizar', 'Youssef'],
  not_in_export: ['status', 'sprint', 'assignee', 'parent links', 'dependencies', 'blockers'],
  summary,
  items,
};
fs.mkdirSync(path.join(root, 'backend', 'data'), { recursive: true });
fs.writeFileSync(path.join(root, 'backend', 'data', 'backlog.json'), `${JSON.stringify(data, null, 2)}\n`);

const label = { implemented: 'Implemented', partial: 'Partial', outstanding: 'Outstanding', process: 'Team process' };
const esc = (s) => String(s || '').replace(/\|/g, '\\|');
const md = [
  '# Requirement Coverage Report (traceability matrix)',
  '',
  '> Generated by `npm run backlog:import` from the Jira export. Do not edit by hand; edit `database/seeders/data/traceability.js`.',
  '>',
  `> Source: ${data.source}. The export has **no status, sprint, assignee, parent or dependency data**, so Jira status is not shown here. The Status column below is the state of the **code in this repository**. Parent links marked *inferred* come from item order and labels, not from Jira. The Excel requirements workbook was not available.`,
  '',
  `Totals: ${summary.epics} epics, ${summary.stories} stories, ${summary.tasks} tasks. Implemented ${summary.implementation.implemented}, partial ${summary.implementation.partial}, outstanding ${summary.implementation.outstanding}, team process ${summary.implementation.process}.`,
  '',
  '| Key | Type | Summary | Parent | Application module | Evidence | Status | Notes |',
  '|---|---|---|---|---|---|---|---|',
  ...items.map((i) => `| ${i.key} | ${i.type} | ${esc(i.summary)} | ${i.parent ? `${i.parent}${i.parent_source === 'inferred' ? ' (inferred)' : ''}` : ''} | ${esc(i.implementation.module)} | ${esc(i.implementation.evidence)} | ${label[i.implementation.status]} | ${esc(i.implementation.notes)} |`),
  '',
];
fs.writeFileSync(path.join(root, 'documentation', 'REQUIREMENTS_COVERAGE.md'), md.join('\n'));
console.log(`Wrote backend/data/backlog.json (${items.length} items) and documentation/REQUIREMENTS_COVERAGE.md`);
